import { copyFile, mkdir, readdir, rm, stat, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join, relative, sep } from "node:path";

const root = fileURLToPath(new URL("../entries/", import.meta.url));
const publicRoot = fileURLToPath(new URL("../.generated-assets/", import.meta.url));
const entries = [];

await rm(publicRoot, { recursive: true, force: true });
await mkdir(publicRoot, { recursive: true });

async function walk(directory) {
	for (const item of await readdir(directory, { withFileTypes: true })) {
		// A local OpenPGP secret-key file is kept out of public assets and listings.
		if (item.name === ".gitkeep" || (directory === root && item.name === "about.txt")) continue;
		const absolutePath = join(directory, item.name);
		if (item.isDirectory()) {
			await walk(absolutePath);
			continue;
		}
		if (!item.isFile()) continue;
		const info = await stat(absolutePath);
		const entryPath = relative(root, absolutePath);
		const publishedPath = join(publicRoot, entryPath);
		await mkdir(dirname(publishedPath), { recursive: true });
		await copyFile(absolutePath, publishedPath);
		entries.push({
			path: entryPath.split(sep).join("/"),
			size: info.size,
			modified: info.mtime.toISOString().slice(0, 16).replace("T", " "),
		});
	}
}

await walk(root);
entries.sort((a, b) => a.path.localeCompare(b.path));
await writeFile(
	new URL("../content-index.js", import.meta.url),
	`// Generated by scripts/build-index.mjs. Do not edit.\nexport default ${JSON.stringify(entries)};\n`,
);
